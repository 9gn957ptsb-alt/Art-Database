def S(name, latin, plan, wiki, c, kind=None, size=1.0, **p):
    p.setdefault("size", size)
    return {"name": name, "latin": latin, "plan": plan, "wiki": wiki, "col": c, "p": p}


def Q(base, name, latin, wiki, c, **over):
    return S(name, latin, "quad", wiki, c, **mix(base, over))


