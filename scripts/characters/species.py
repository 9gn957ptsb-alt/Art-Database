def lives_at(key, lat, lon):
    inside = lambda bs: any(a <= lat <= b and c <= lon <= d for a, b, c, d in bs)
    if key in RANGE and not inside(RANGE[key]):
        return False
    return not (key in GAPS and inside(GAPS[key]))
